SHEAR = 0.22  # horizontal shift per row, in dot pitches


def layout(text, pitch, font=SMALL, gap=1, shear=SHEAR):
    """Place the dots of `text`.

    pitch: distance between neighbouring dot centres
    gap:   empty columns between letters
    Returns (points, width, height); points are dot centres relative to the
    first possible dot, width/height span the outermost dot centres.
    """
    rows = len(font["A"])
    cols = len(font["A"][0])
    points, x = [], 0.0
    for ch in text.upper():
        for r, row in enumerate(font.get(ch, ())):
            for c, bit in enumerate(row):
                if bit == "1":
                    points.append((x + c * pitch + (rows - 1 - r) * pitch * shear, r * pitch))
        x += (cols + gap) * pitch
    width = x - (gap + 1) * pitch + (rows - 1) * pitch * shear
    return points, width, (rows - 1) * pitch


def svg_text(text, x, y, pitch, r, fill, anchor="start"):
    """SVG <g> of circles. (x, y) is the top-left (or top-right with
    anchor="end") corner of the text including the dot radius.
    Returns (svg, total_width, total_height)."""
    points, w, h = layout(text, pitch)
    if anchor == "end":
        x -= w + 2 * r
    circles = "".join(f'<circle cx="{x + px + r:.1f}" cy="{y + py + r:.1f}" r="{r}"/>' for px, py in points)
    return f'<g fill="{fill}">{circles}</g>', w + 2 * r, h + 2 * r
